//! The HALT-bug program (`tests/halt_bug_locks.rs`), shared with `examples/halt_bug_rom.rs`,
//! which writes it as a ROM file for the runner's proof. After each call it logs A at
//! `LOG` + n (n mod 256): 0x3E when both reads of `LD A,n`'s opcode returned it, 0xFF when
//! OAM's read lock rose between them, 0x01 when the opcode's own read was locked (RST 38H).

/// The log's first address, in work RAM.
pub const LOG: u16 = 0xC000;

pub fn program() -> Vec<u8> {
    let mut rom = vec![0u8; 0x8000];
    rom[0x100..0x103].copy_from_slice(&[0xC3, 0x50, 0x01]);
    // RST 38H, which a call runs when an opcode of the routine reads 0xFF: drop the return
    // into the routine and return to the call.
    rom[0x38..0x3B].copy_from_slice(&[0x33, 0x33, 0xC9]);
    let routine = |at: &mut Vec<u8>| at.extend([0x01, 0x01, 0xFE, 0x3E, 0x76, 0x02, 0x0C, 0x3E, 0x3E, 0x02, 0x0C, 0x3E, 0x5A, 0x02, 0x0C, 0x3E, 0xC9, 0x02]);
    let mut code = vec![0xF3, 0x31, 0xFE, 0xFF, 0xAF, 0xE0, 0x40]; // DI; LD SP,$FFFE; LCD off
    routine(&mut code); // HALT; LD A,$5A; RET at $FE01
    code.extend([0x3E, 0x01, 0xE0, 0xFF, 0x3E, 0x93, 0xE0, 0x40, 0x1E, 0x00, 0x16, 0x00]); // IE = 1; LCD on; E = 0; D = 0
    code.extend([0x21, LOG as u8, (LOG >> 8) as u8]); // HL = LOG
    let main = code.len();
    code.extend([
        0xF0, 0x44, 0xBB, 0x20, 0xFB, // wait for LY = E
        0x7A, 0x0F, 0x0F, 0xE6, 0x1F, 0xC6, 0x13, 0x3D, 0x20, 0xFD, // (D >> 2) + $13 loops
        0xCB, 0x42, 0x20, 0x00, 0xCB, 0x4A, 0x20, 0x00, 0xCB, 0x4A, 0x20, 0x00, // D & 3 M-cycles
        0x3E, 0x01, 0xE0, 0x0F, 0xD5, 0xCD, 0x01, 0xFE, 0xD1, // IF = 1; PUSH DE; CALL $FE01; POP DE
        0x77, 0x2C, // LD (HL),A; INC L
        0xF0, 0x41, 0xE6, 0x03, 0xFE, 0x03, 0x20, 0xF8, 0xF0, 0x41, 0xE6, 0x03, 0x20, 0xFA, // to mode 3, then mode 0
    ]);
    routine(&mut code); // the routine again, which the OAM corruption bug may have rewritten
    code.extend([0x7B, 0xC6, 0x05, 0xFE, 0x90, 0x38, 0x02, 0xD6, 0x90, 0x5F, 0x7A, 0x3C, 0xE6, 0x7F, 0x57]); // E = (E + 5) mod 144; D = (D + 1) & 127
    let back = main as i64 - (code.len() as i64 + 2);
    code.extend([0x18, back as i8 as u8]);
    rom[0x150..0x150 + code.len()].copy_from_slice(&code);
    rom
}
